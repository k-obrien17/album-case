/**
 * Export the owner's highest-rated album per release year to keithrobrien.com's
 * /collect/[year] highlight row.
 *
 * Read-only over Turso, same source data as export-collect-albums.mjs (the
 * ranking_snapshots table) but grouped by release_year and keeping only the
 * top-rated album per year, instead of a flat top-N.
 *
 * Usage:
 *   node --env-file=web/.env.local web/scripts/export-album-of-year.mjs
 *   COLLECT_OUT=/abs/path/album-of-year.json node --env-file=web/.env.local web/scripts/export-album-of-year.mjs
 */
import { createClient } from '@libsql/client';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname } from 'node:path';

// Matches web/src/owner.ts's OWNER_ID. Duplicated, not imported: this is a
// plain Node ESM script with no TS loader, so it can't import a .ts file.
const OWNER_ID = 'c0ffee00-0000-4000-8000-000000000001';

function db() {
  const url = process.env.TURSO_DATABASE_URL;
  const authToken = process.env.TURSO_AUTH_TOKEN;
  if (!url || !authToken) {
    console.error('Missing TURSO_DATABASE_URL / TURSO_AUTH_TOKEN. Run `vercel env pull web/.env.local` first.');
    process.exit(1);
  }
  return createClient({ url, authToken });
}

const client = db();
const rows = await client.execute({
  sql: 'SELECT ranking_json FROM ranking_snapshots WHERE session_id = ?',
  args: [OWNER_ID],
});

const row = rows.rows[0];
if (!row) {
  console.error('No ranking snapshot found for the owner session.');
  process.exit(1);
}

const ranked = JSON.parse(String(row.ranking_json));

// Same hardcoded-default convention as export-collect-albums.mjs, for the
// same reason: robust regardless of where the repo happens to be checked out.
const OUT =
  process.env.COLLECT_OUT ||
  '/Users/keithobrien/Desktop/Claude/Projects/keithrobrien/content/collect/album-of-year.json';

if (!existsSync(dirname(OUT))) {
  console.error(`Output directory does not exist: ${dirname(OUT)}. Set COLLECT_OUT to a valid path.`);
  process.exit(1);
}

const rated = ranked.filter(
  (a) => typeof a.rating === 'number' && !Number.isNaN(a.rating) && a.release_year,
);

const byYear = {};
for (const album of rated) {
  const y = String(album.release_year);
  if (!byYear[y] || album.rating > byYear[y].score) {
    byYear[y] = {
      title: album.title,
      artist: album.primary_artist_name,
      year: album.release_year,
      score: album.rating,
      mb_url: `https://musicbrainz.org/release-group/${album.mbid}`,
      cover_url: album.cover_url ?? null,
    };
  }
}

const payload = {
  generated_at: new Date().toISOString().slice(0, 10),
  source: 'album-case',
  note: 'Generated by album-case/web/scripts/export-album-of-year.mjs. Do not hand-edit.',
  by_year: byYear,
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, JSON.stringify(payload, null, 2) + '\n');
console.log(`Wrote ${Object.keys(byYear).length} years to ${OUT}`);

client.close();
